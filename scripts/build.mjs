/**
 * Build the browser artifact for dsh-tapeout-3d-lab.
 *
 * The Harness Web module system loads a plugin's `./client` export as one script that
 * calls `window.__ModuleLoader__.load({ id, factory })`. The factory is CJS-shaped and
 * receives `require`, so the bundle is a single closure. We concatenate our source
 * files in order inside that closure: they share one `TT` namespace and one React.
 *
 * Usage: node scripts/build.mjs [--check]
 *   --check validates that every source file parses (syntax only) and prints sizes.
 */
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const ID = 'dsh-tapeout-3d-lab'
const SOURCES = [
  '00-core.js',
  '10-engine.js',
  '15-parts.js',
  '20-circuit.js',
  '25-cpu.js',
  '28-safety.js',
  '30-missions.js',
  '35-lab.js',
  '36-audio.js',
  '37-arcade.js',
  '38-export.js',
  '39-hardware.js',
  '41-access.js',
  '42-lottery.js',
  '40-ui.js',
  '50-app.js',
]

const check = process.argv.includes('--check')
const parts = []
const missing = []

for (const name of SOURCES) {
  const path = join(root, 'src', 'client', name)
  if (!existsSync(path)) {
    missing.push(name)
    continue
  }
  const text = readFileSync(path, 'utf8')
  // Syntax check the file on its own with its expected free variables.
  try {
    // Parse only: free variables (TT, React, …) are resolved at runtime, never here.
    new Function(text) // eslint-disable-line no-new-func
  } catch (error) {
    console.error(`[build] syntax error in ${name}: ${error.message}`)
    process.exitCode = 1
    process.exit(1)
  }
  parts.push(`// ---- ${name} ----\n${text.trim()}\n`)
  console.log(`[build] ${name.padEnd(16)} ${String(statSync(path).size).padStart(7)} bytes`)
}

if (missing.length > 0) {
  console.log(`[build] skipping not-yet-written sources: ${missing.join(', ')}`)
}

const body = parts.join('\n')

try {
  new Function('React', 'module', 'exports', 'require', body) // eslint-disable-line no-new-func
} catch (error) {
  console.error(`[build] syntax error in combined bundle: ${error.message}`)
  process.exit(1)
}

const artifact = `/* dsh-tapeout-3d-lab — generated by scripts/build.mjs; do not edit by hand */
window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}, factory: (require) => {
  const module = { exports: {} };
  const exports = module.exports;
  const React = require("react");
  ${body}
  return TT.plugin;
}});
`

const out = join(root, 'client.js')
if (check) {
  console.log(`[build] check ok; would write ${artifact.length} bytes to client.js`)
} else {
  writeFileSync(out, artifact)
  console.log(`[build] wrote client.js (${artifact.length} bytes)`)
}
