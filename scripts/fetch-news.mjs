#!/usr/bin/env node
/**
 * Crawl the public TapeOut news page and write a snapshot into src/client/news-feed.js.
 * tapeout.link sits behind Cloudflare, so the crawl goes through the r.jina.ai reader
 * (plain text extraction). Re-run with `npm run news` to refresh the embedded snapshot.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SOURCE = 'https://tapeout.link/news'
const READER = 'https://r.jina.ai/' + SOURCE

function clean(text) {
  return String(text || '').replace(/\s+/g, ' ').trim()
}

function splitBilingual(title) {
  // Titles often repeat in Chinese and English; keep everything up to the last CJK
  // character when English text follows it.
  const text = clean(title)
  let last = -1
  for (let index = 0; index < text.length; index += 1) {
    if (/[\u4e00-\u9fff]/.test(text[index])) last = index
  }
  if (last > 3 && /[A-Za-z]/.test(text.slice(last + 1))) return text.slice(0, last + 1)
  return text
}

function parse(markdown) {
  const lines = String(markdown).split('\n')
  const items = []
  let currentDate = ''
  let currentTime = ''
  let pending = null
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim()
    const date = line.match(/^##\s*(.+?)(?:\s*·.*)?$/)
    if (date && /月|Nov|Dec|Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct/.test(date[1])) currentDate = clean(date[1])
    const time = line.match(/^\d+\.\s+(\d{2}:\d{2})$/)
    if (time) currentTime = time[1]
    const heading = line.match(/^###\s*\[(.+?)\]\((https:\/\/tapeout\.link\/news\/\d+)\)/)
    if (heading) {
      if (pending) items.push(pending)
      pending = { title: splitBilingual(heading[1]), url: heading[2], time: currentTime, date: currentDate, summary: '' }
      continue
    }
    if (pending && !pending.summary && line && !line.startsWith('!') && !line.startsWith('*') && !line.startsWith('展开') && !/^###/.test(line) && !/^\d+\.\s+/.test(line)) {
      if (line.length > 30) pending.summary = clean(line).slice(0, 240)
    }
  }
  if (pending) items.push(pending)
  return items.slice(0, 14)
}

const response = await fetch(READER, { headers: { 'user-agent': 'Mozilla/5.0 (compatible; dsh-tapelab-news/1.0)' } })
if (!response.ok) throw new Error(`crawl failed: HTTP ${response.status}`)
const markdown = await response.text()
const items = parse(markdown)
if (!items.length) throw new Error('no items parsed from tapeout.link/news')

const payload = {
  source: SOURCE,
  crawledAt: new Date().toISOString(),
  items,
}
const out = join(HERE, '..', 'src', 'client', 'news-feed.js')
writeFileSync(out, `/** Generated by scripts/fetch-news.mjs — do not edit by hand. */\nTT.NewsFeed = ${JSON.stringify(payload, null, 2)}\n`)
console.log(`wrote ${items.length} items to src/client/news-feed.js`)
for (const item of items.slice(0, 5)) console.log(`- ${item.title} (${item.time})`)
